import assert from "node:assert/strict";
import { initialDiscovery, nextDiscoveryQuestion, recordUserInput, syncIdeaFacts } from "../src/services/ai/discovery";
import { buildGroundedGraph, reconcileGraph } from "../src/services/ai/reconcileGraph";
import { useWorkspaceStore } from "../src/store/useWorkspaceStore";

const user = (id: string, text: string) => ({ id, role: "user" as const, text, createdAt: new Date().toISOString() });
const business = recordUserInput(initialDiscovery(), user("a", "Quiero abrir una ferretería local que venda materiales a vecinos"));
assert.equal(business.archetype, "business");
assert.equal(business.lifecycle, "ready");
assert.equal(nextDiscoveryQuestion(business).length, 0);
const budgetRequest = recordUserInput(business, user("budget", "Ya sé qué vender, quiero analizar mi presupuesto"));
assert.equal(budgetRequest.candidateDefinitionVersion, business.candidateDefinitionVersion);
const software = recordUserInput(initialDiscovery(), user("b", "Quiero desarrollar una aplicación nueva"));
assert.equal(software.archetype, "software");
assert.equal(software.lifecycle, "discovering");
assert.equal(nextDiscoveryQuestion(software)[0].id, "topic:problem");
const answered = recordUserInput(software, { ...user("c", "Respuestas al cuestionario"), questionnaireId: "q1", answers: { "topic:problem": "Ayudar a pacientes a pedir citas" } });
assert.equal(answered.lifecycle, "ready");
assert.equal(nextDiscoveryQuestion(answered).length, 0);
const shortAnswer = recordUserInput(software, user("short", "Vender tornillos"));
assert.equal(shortAnswer.facts.find((fact) => fact.key === "problem")?.value, "Vender tornillos");
assert.equal(shortAnswer.lifecycle, "ready");
const unknownAnswer = recordUserInput(software, user("unknown", "No sé"));
assert.equal(unknownAnswer.facts.find((fact) => fact.key === "problem")?.status, "unknown");
assert.equal(unknownAnswer.lifecycle, "ready");
const corrected = recordUserInput({ ...business, lifecycle: "generated" }, user("correction", "En realidad quiero hacer una aplicación"));
assert.equal(corrected.lifecycle, "discovering");
assert.notEqual(corrected.candidateDefinitionVersion, business.candidateDefinitionVersion);
const proposed = syncIdeaFacts(business, { type: "idea_cards", title: "Ideas", items: [{ id: "x", title: "Asesoría", description: "Ayuda al cliente", benefits: [], resources: [], relations: [], status: "pending" }] }, "assistant-idea");
assert.equal(proposed.facts.find((fact) => fact.key === "suggestion:assistant-idea:x")?.status, "unconfirmed");
assert.equal(proposed.candidateDefinitionVersion, business.candidateDefinitionVersion);
const approved = syncIdeaFacts(proposed, { type: "idea_cards", title: "Ideas", items: [{ id: "x", title: "Asesoría", description: "Ayuda al cliente", benefits: [], resources: [], relations: [], status: "approved" }] }, "assistant-idea");
assert.equal(approved.facts.find((fact) => fact.key === "suggestion:assistant-idea:x")?.status, "confirmed");
assert.equal(approved.candidateDefinitionVersion, business.candidateDefinitionVersion);
const graph = buildGroundedGraph(business, "Ferretería");
assert.ok(graph.nodes.every((node) => node.description.includes("ferretería") || node.verification === "unknown"));
const applied = reconcileGraph({ nodes: [], relations: [] }, graph, business, business.candidateDefinitionVersion!);
assert.equal(applied.nodes.length, graph.nodes.length);
const repeated = reconcileGraph(applied, graph, business, business.candidateDefinitionVersion!);
assert.equal(repeated.nodes.length, applied.nodes.length);
const edited = reconcileGraph({ nodes: applied.nodes.map((node, index) => index === 0 ? { ...node, x: 999, title: "Mi título", manuallyEditedFields: ["title"] } : node), relations: applied.relations }, graph, business, business.candidateDefinitionVersion!);
assert.equal(edited.nodes[0].x, 999);
assert.equal(edited.nodes[0].title, "Mi título");
const deleted = reconcileGraph({ nodes: [], relations: [] }, graph, { ...business, tombstones: [graph.nodes[0].semanticKey!] }, business.candidateDefinitionVersion!);
assert.ok(deleted.nodes.every((node) => node.semanticKey !== graph.nodes[0].semanticKey));
assert.ok(deleted.nodes.every((node) => node.verification === "unknown"));
const project = { id: "test-project", name: "Ferretería", description: "", status: "draft" as const, icon: "lightbulb" as const, updatedAt: new Date().toISOString(), nodeCount: applied.nodes.length };
const conversation = [user("a", "Quiero abrir una ferretería local que venda materiales a vecinos")];
const savedWorkspace = { project, map: applied, messages: conversation, discovery: { ...business, lifecycle: "generated" as const, completionAnchorMessageId: "a" } };
useWorkspaceStore.getState().setWorkspace(savedWorkspace);
useWorkspaceStore.getState().setWorkspace(savedWorkspace);
const state = useWorkspaceStore.getState();
assert.equal(state.discoveryMessages.filter((message) => message.type === "ready").length, 1);
assert.deepEqual(state.spatialNodes.map((node) => node.id).sort(), applied.nodes.map((node) => node.id).sort());
assert.deepEqual(state.spatialLinks.map((link) => link.id).sort(), applied.relations.map((relation) => relation.id).sort());
console.log("Discovery readiness, graph grounding, reconciliation and tombstones passed.");
